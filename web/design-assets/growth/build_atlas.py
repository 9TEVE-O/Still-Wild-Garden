"""Build the five-stage growth atlas and its TypeScript index for the web renderer.

Run from anywhere:  python3 web/design-assets/growth/build_atlas.py
Writes:
  web/public/art/growth/stillwild-growth-atlas.png   sprites at 1x logical pixels, transparent
  web/lib/growth-atlas.ts                           sprite rectangles, base points and planting spots
Needs numpy, Pillow and scipy. Output is deterministic for a given island and sapling original.
"""
from pathlib import Path
import hashlib, json
import numpy as np
from PIL import Image
import plants, ground
from sapling_from_art import reduce

HERE = Path(__file__).resolve().parent
WEB = HERE.parent.parent
ATLAS_PNG = WEB / "public/art/growth/stillwild-growth-atlas.png"
ATLAS_TS = WEB / "lib/growth-atlas.ts"
SHRUB_SIZES = (0.9, 1.0, 1.1, 1.2, 1.3, 1.4)
VARIANTS = 4
MAX_ROW = 256

def trim(rgba, bx, by):
    ys, xs = np.nonzero(rgba[..., 3])
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    return rgba[y0:y1, x0:x1], bx - x0, by - y0

def sprites():
    groups = {}
    groups["mound:0"] = [plants.make_mound(seed) for seed in range(1, VARIANTS + 1)]
    groups["sprout:0"] = [plants.make_sprout(seed) for seed in range(1, VARIANTS + 1)]
    for i, h in enumerate((17, 19)):                  # smaller saplings toward the back of the island
        art = reduce(h)
        groups[f"sapling:{i}"] = [plants.make_sapling(art, mirror) for mirror in (False, True)]
    for i, size in enumerate(SHRUB_SIZES):
        for stage, flowering in (("shrub", False), ("flowering", True)):
            groups[f"{stage}:{i}"] = [plants.make_shrub(100 * i + seed, size, flowering)
                                      for seed in range(1, VARIANTS + 1)]
    return {k: [trim(*s) for s in v] for k, v in groups.items()}

def pack(groups):
    items = [(k, i, s) for k, v in groups.items() for i, s in enumerate(v)]
    items.sort(key=lambda it: (-it[2][0].shape[0], it[0], it[1]))
    x = y = row_h = 0
    places = {}
    for key, i, (arr, bx, by) in items:
        h, w = arr.shape[:2]
        if x + w + 1 > MAX_ROW:
            x, y, row_h = 0, y + row_h + 1, 0
        places[(key, i)] = (x, y)
        x += w + 1
        row_h = max(row_h, h)
    atlas = np.zeros((y + row_h, MAX_ROW, 4), np.uint8)
    cells = {k: [None] * len(v) for k, v in groups.items()}
    for key, i, (arr, bx, by) in items:
        px, py = places[(key, i)]
        h, w = arr.shape[:2]
        atlas[py:py + h, px:px + w] = arr
        cells[key][i] = (int(px), int(py), int(w), int(h), int(bx), int(by))
    return atlas, cells

def main():
    groups = sprites()
    atlas, cells = pack(groups)
    ATLAS_PNG.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(atlas, "RGBA").save(ATLAS_PNG, optimize=True)
    spots = ground.plant_spots(ground.ground_mask())
    W, H = ground.SIZE
    norm = [(round(x / W, 5), round(y / H, 5)) for x, y in spots]
    digest = hashlib.sha256(ATLAS_PNG.read_bytes()).hexdigest()
    lines = [
        "// Generated by web/design-assets/growth/build_atlas.py. Do not edit by hand.",
        "// Sprites are 1x logical pixels; one logical pixel is 3 px of the 1536-wide island original.",
        f'export const GROWTH_ATLAS_SRC = "/art/growth/stillwild-growth-atlas.png";',
        f'export const GROWTH_ATLAS_SHA256 = "{digest}";',
        "export const ISLAND_SOURCE_WIDTH = 1536;",
        "export const LOGICAL_PIXEL = 3;",
        f"export const SHRUB_SIZES = {json.dumps(list(SHRUB_SIZES))} as const;",
        "/** [x, y, width, height, baseX, baseY] in atlas pixels; the base is where the plant meets the ground. */",
        "export type SpriteCell = readonly [number, number, number, number, number, number];",
        "export const GROWTH_SPRITES: Readonly<Record<string, readonly SpriteCell[]>> = {",
    ]
    for key, v in cells.items():
        lines.append(f'  "{key}": [{", ".join(json.dumps(list(c)) for c in v)}],')
    lines += [
        "};",
        f"/** Island-relative [x, y] (0..1) of {len(norm)} planting spots on open ground, sorted by y. */",
        "export const GROWTH_SPOTS: readonly (readonly [number, number])[] = [",
    ]
    for i in range(0, len(norm), 6):
        lines.append("  " + ", ".join(json.dumps(list(p)) for p in norm[i:i + 6]) + ",")
    mx, my = ground.FIRST_SPROUT
    lines += ["];", f"export const FIRST_SPROUT = [{round(mx / W, 5)}, {round(my / H, 5)}] as const;", ""]
    ATLAS_TS.write_text("\n".join(lines))
    print(json.dumps({"atlas": str(ATLAS_PNG.relative_to(WEB)), "size": atlas.shape[1::-1], "sprites": sum(len(v) for v in cells.values()),
                      "spots": len(norm), "sha256": digest}))

if __name__ == "__main__":
    main()
